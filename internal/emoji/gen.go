//go:build ignore

// gen writes names_gen.go, Slack's emoji names, from iamcal/emoji-data
// (MIT), the table Slack itself uses:
//
//	go run gen.go [emoji.json]
//
// Without an argument it downloads the table.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const src = "https://raw.githubusercontent.com/iamcal/emoji-data/master/emoji.json"

type entry struct {
	Unified    string   `json:"unified"`
	ShortName  string   `json:"short_name"`
	ShortNames []string `json:"short_names"`
	Obsoleted  string   `json:"obsoleted_by"`
}

func main() {
	var raw []byte
	var err error
	if len(os.Args) > 1 {
		raw, err = os.ReadFile(os.Args[1])
	} else {
		var resp *http.Response
		if resp, err = http.Get(src); err == nil {
			defer resp.Body.Close()
			raw, err = io.ReadAll(resp.Body)
		}
	}
	if err != nil {
		fail(err)
	}
	var all []entry
	if err := json.Unmarshal(raw, &all); err != nil {
		fail(err)
	}
	glyphs := map[string]string{}
	names := map[string]string{}
	for _, e := range all {
		var g strings.Builder
		for _, cp := range strings.Split(e.Unified, "-") {
			r, err := strconv.ParseUint(cp, 16, 32)
			if err != nil {
				fail(err)
			}
			g.WriteRune(rune(r))
		}
		for _, n := range e.ShortNames {
			glyphs[n] = g.String()
		}
		if e.Obsoleted == "" {
			names[g.String()] = e.ShortName
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen.go from iamcal/emoji-data. DO NOT EDIT.\n\npackage emoji\n\n")
	b.WriteString("// glyphs maps every Slack emoji name to its character.\nvar glyphs = map[string]string{\n")
	for _, k := range sorted(glyphs) {
		fmt.Fprintf(&b, "%q: %q,\n", k, glyphs[k])
	}
	b.WriteString("}\n\n// names maps a character back to its Slack name.\nvar names = map[string]string{\n")
	for _, k := range sorted(names) {
		fmt.Fprintf(&b, "%q: %q,\n", k, names[k])
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("names_gen.go", out, 0o644); err != nil {
		fail(err)
	}
}

func sorted(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
